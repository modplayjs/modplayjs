function mulShift32(sq, sample) {
  const hi = Math.floor(sq / 65536);
  const lo = sq - hi * 65536;
  const hiPart = hi * sample;
  const loPart = lo * sample;
  const q = Math.floor(hiPart / 65536);
  const rem = hiPart - q * 65536;
  return q + Math.floor((rem * 65536 + loPart) / 4294967296);
}
