function nativeOf(xxs) {
  let nat = nativeCache.get(xxs);
  if (nat) return nat;
  const bits16 = (xxs.flags & SampleFlags.BITS16) !== 0;
  const stereo = (xxs.flags & SampleFlags.STEREO) !== 0;
  const chn = stereo ? 2 : 1;
  const len = xxs.length * chn;
  const scale = bits16 ? 32768 : 128;
  if (bits16) {
    const buf = new Int16Array(2 + len + TAIL_SLOTS * chn);
    for (let i = 0; i < len; i++) {
      let v = Math.round((xxs.data[i] ?? 0) * scale);
      if (v > 32767) v = 32767;
      else if (v < -32768) v = -32768;
      buf[2 + i] = v;
    }
    nat = { data: buf, pre: 2 };
  } else {
    const buf = new Int8Array(4 + len + TAIL_SLOTS * chn);
    for (let i = 0; i < len; i++) {
      let v = Math.round((xxs.data[i] ?? 0) * scale);
      if (v > 127) v = 127;
      else if (v < -128) v = -128;
      buf[4 + i] = v;
    }
    nat = { data: buf, pre: 4 };
  }
  const nat2 = nat;
  const sptr = nat2.data;
  const pre = nat2.pre;
  const tailSlots = 4 * chn;
  for (let i = 0; i < tailSlots; i++) {
    sptr[pre + len + i] = sptr[pre + len - chn + i % chn];
  }
  for (let i = 1; i <= pre; i++) {
    sptr[pre - i] = sptr[pre + (pre - i) % chn];
  }
  nativeCache.set(xxs, nat);
  return nat;
}
